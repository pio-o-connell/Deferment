CREATE TABLE lecturer (
    Lect_ID VARCHAR(10) PRIMARY KEY,
    Firstname VARCHAR(20) NOT NULL,
    Surname VARCHAR(30) NOT NULL,
    Lecturer_Email VARCHAR(30) NOT NULL
);

CREATE TABLE student (
    Student_ID VARCHAR(10) PRIMARY KEY,
    Firstname VARCHAR(20) NOT NULL,
    Surname VARCHAR(30) NOT NULL,
    Student_Email VARCHAR(30)
);

CREATE TABLE programme (
    Programme_ID VARCHAR(20) PRIMARY KEY,
    Num_Years INTEGER NOT NULL,
    Coord_ID VARCHAR(10) NOT NULL REFERENCES lecturer(Lect_ID) ON DELETE CASCADE,
    Prog_Year INTEGER NOT NULL
);

CREATE TABLE semester (
    Semester_ID VARCHAR(20) PRIMARY KEY,
    Programme_ID VARCHAR(20) REFERENCES programme(Programme_ID) ON DELETE CASCADE,
    StartDate VARCHAR(4) NOT NULL,
    FinishDate VARCHAR(3) NOT NULL
);

CREATE TABLE modules (
    Module_ID VARCHAR(10) NOT NULL,
    CRN INTEGER NOT NULL UNIQUE,
    Name VARCHAR(45) NOT NULL,
    Lect_ID VARCHAR(20) NOT NULL REFERENCES lecturer(Lect_ID) ON DELETE CASCADE,
    Semester_ID VARCHAR(20) NOT NULL REFERENCES semester(Semester_ID) ON DELETE CASCADE,
    PRIMARY KEY (Module_ID, CRN)
);

CREATE TABLE registration (
    Student_ID VARCHAR(10) NOT NULL REFERENCES student(Student_ID) ON DELETE CASCADE,
    CRN INTEGER NOT NULL REFERENCES modules(CRN) ON DELETE CASCADE,
    Programme_ID VARCHAR(20) NOT NULL REFERENCES programme(Programme_ID) ON DELETE CASCADE,
    PRIMARY KEY (Student_ID, CRN)
);

CREATE TABLE deferrals (
    Def_ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Student_ID VARCHAR(10) NOT NULL REFERENCES student(Student_ID) ON DELETE CASCADE,
    Lect_ID VARCHAR(10) NOT NULL,
    Programme_ID VARCHAR(20) NOT NULL REFERENCES programme(Programme_ID) ON DELETE CASCADE,
    Module_ID VARCHAR(10) NOT NULL,
    Approved VARCHAR_IGNORECASE(10) DEFAULT 'False' NOT NULL
);

CREATE TABLE users (
    USER_ID INTEGER PRIMARY KEY,
    USERNAME VARCHAR(45) NOT NULL,
    PASSWORD VARCHAR(45) NOT NULL,
    ENABLED BOOLEAN NOT NULL
);

CREATE TABLE user_roles (
    USER_ROLE_ID INTEGER PRIMARY KEY,
    USER_ID INTEGER NOT NULL REFERENCES users(USER_ID),
    AUTHORITY VARCHAR(45) NOT NULL
);
